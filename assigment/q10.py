# Take a month number (1–12) and print the number of days in that month (ignore leap
# years).
month_num=int(input("enter your number"))
if(month_num==1):
    print("january")
elif(month_num==2):
    print("february")
elif(month_num==3):
    print("march")
elif(month_num==4):
    print("april")
elif(month_num==5):
    print("may")
elif(month_num==6):
    print("june")
elif(month_num==7):
    print("july")
elif(month_num==8):
    print("august")
elif(month_num==9):
    print("september")
elif(month_num==10):
    print("october")
elif(month_num==11):
    print("november")
elif(month_num==12):
    print("december")
else:
    print("invalid")